#Inicialização da calculadora
print("-----------------------------------------------------CALCULADORA EM PYTHON------------------------------------------------------")

#inicializando variável de término do programa
terminar_programa = 'n'

#Loop para seleção de operação que continua rodando até que o usuário escolha sair
while terminar_programa != 's':

  #seleção da operação pelo usuário
  operacao = input('Escolha a operação: \n 1. Adição \n 2. Subtração \n 3. Multiplicação \n 4. Divisão \n')

  #seleção de 2 números pelo usuário
  num1 = float(input('Digite o primeiro número: '))
  num2 = float(input('Digite o segundo número: '))

  #condicional que devolde o resultado referente a operação escolhida pelo usuário
  if operacao == '1':
    resultado = int(num1 + num2)
  elif operacao == '2':
    resultado = int(num1 - num2)
  elif operacao == '3':
    resultado = int(num1 * num2)
  elif operacao == '4':
    resultado = num1 / num2
  else:
    print('Operação inválida')

  print(f'O resultado é: {resultado}')

  #pergunta se o usuário deseja sair da calculadora
  terminar_programa = input('Você deseja sair? \n (s ou n) \n\n')

  #Caso o usuário queira sair, o programa print na tela 'programa finalizado'
  if terminar_programa == 's':
    print('\n ------------------------------------------PROGRAMA FINALIZADO-------------------------------------------------------')